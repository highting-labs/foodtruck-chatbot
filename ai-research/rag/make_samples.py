def main():
    out = os.path.join(os.path.dirname(__file__), 'sample_data', 'kakao')
    os.makedirs(out, exist_ok=True)
    for i, (cust, day, msgs) in enumerate(CONVS, 1):
        with open(os.path.join(out, f'대화_S{i:03d}.csv'), 'w', encoding='utf-8-sig', newline='') as f:
            w = csv.writer(f)
            w.writerow(['DATE', 'USER', 'MESSAGE'])
            for j, (who, text) in enumerate(msgs):
                w.writerow([f'{day} {10 + j // 2:02d}:{(j * 7) % 60:02d}:00', STAFF if who == 's' else cust, text])
    print('samples', len(CONVS), '->', out)


if __name__ == '__main__':
    main()
